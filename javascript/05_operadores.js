console.log("Después de c += 5:", c);
c -= 3; // c = c - 3
console.log("Después de c -= 3:", c);
c *= 2; // c = c * 2
console.log("Después de c *= 2:", c);
c /= 4; // c = c / 4
console.log("Después de c /= 4:", c);
c %= 3; // c = c % 3
console.log("Después de c %= 3:", c);

